#!/usr/bin/env bash
# Одноразовая живая проверка «контроллер автоматически восстанавливает
# локализацию»: откатываем установленную копию к английской → вы открываете
# контроллер (или жмёте «Запуск») → скрипт проверяет, что локализация вернулась
# до запуска Freebuff, и что цепочка английских бэкапов не испорчена.
#
# ВНИМАНИЕ: этот скрипт относится к китайскому пакету локализации (каталог
# hanhua/ со сборкой output/). Русская сборка этот пакет не поставляет, поэтому
# здесь он всегда завершится с ошибкой «не найден репозиторий локализации».
#
# Использование (сначала полностью закройте Freebuff, затем):
#   bash tools/verify-autorestore.sh            # вручную: вы жмёте «Запуск»
#   bash tools/verify-autorestore.sh --auto     # полностью автоматически: скрипт
#                                               #   сам запускает контроллер (v1.8.17+),
#                                               #   восстановление срабатывает при открытии
#
# Почему нужно закрыть приложение: первая проверка автовосстановления — «не
# запущен ни один экземпляр». Режим --auto превращает всю процедуру в одну
# команду, удобно запускать без присмотра (результат пишется в лог).
set -euo pipefail

AUTO=0
case "${1:-}" in
  --auto) AUTO=1 ;;
  "") ;;
  *) echo "Использование: bash tools/verify-autorestore.sh [--auto]" >&2; exit 2 ;;
esac

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
# Результат дублируется в verify-autorestore.log: проверка требует полностью
# закрыть Freebuff (включая текущий клиент), и после её завершения терминала
# обычно уже не видно. VERIFY_NOLOG=1 отключает эту копию.
if [ -z "${VERIFY_NOLOG:-}" ]; then
  exec > >(tee -a "${HERE}/verify-autorestore.log") 2>&1
fi
INSTALL="${LOCALAPPDATA:-}/Programs/@codebufffreebuff-desktop"
R="${INSTALL}/resources"
UI="${R}/orchestrator/ui"
CTRL="${HERE}/FreebuffController.exe"

fail() { echo "ERROR: $*" >&2; sleep 0.3 2>/dev/null || true; exit 1; }  # даём tee дописать, не обрезая лог
sha() { sha256sum "$1" 2>/dev/null | cut -d' ' -f1; }

# --- 0. Предусловие: приложение должно быть полностью закрыто (это же и первая
#        проверка автовосстановления) ----------------------------------------
if tasklist //FI "IMAGENAME eq Freebuff.exe" 2>/dev/null | grep -q 'Freebuff\.exe'; then
  fail "Freebuff всё ещё запущен. Полностью закройте его (включая все экземпляры) и повторите.
  Подсказка: автовосстановление срабатывает только когда не запущен ни один
  экземпляр, поэтому с открытым приложением проверка ничего не покажет."
fi
[ -f "${UI}/index.html" ] || fail "Не найден установленный UI: ${UI}/index.html"
[ -f "${CTRL}" ] || fail "Не найден exe контроллера: ${CTRL} (сначала соберите: bash build.bat)"

# Версия контроллера: exe ниже 1.8.4 не умеет автовосстановление
CTRL_VER="$(powershell -NoProfile -Command "(Get-Item '${CTRL}').VersionInfo.FileVersion" 2>/dev/null | tr -d '\r' || true)"
echo "Контроллер: ${CTRL}  версия ${CTRL_VER:-неизвестно}"

# --- Ищем репозиторий локализации (тот же порядок, что и в контроллере:
#     hanhua/ или freebuff-zh/ рядом или уровнем выше) ------------------------
HANHUA=""
for p in "${HERE}/hanhua" "${HERE}/../hanhua" "${HERE}/freebuff-zh" "${HERE}/../freebuff-zh"; do
  [ -f "${p}/dict.json" ] && { HANHUA="$(cd "$p" && pwd)"; break; }
done
[ -n "${HANHUA}" ] || fail "Не найден репозиторий локализации (hanhua/ или freebuff-zh/ с dict.json)."
echo "Репозиторий локализации: ${HANHUA}"
[ -f "${HANHUA}/output/app.asar" ] || fail "В ${HANHUA}/output нет собранного артефакта, сначала bash build.sh."

# --- 1. Запоминаем базовое состояние и откатываем к английской версии ----------
echo
echo "== 1/3 откат к английской оригиналу =="
BK_BEFORE="$(ls -1dt "${R}"/hanhua-backup-* 2>/dev/null | head -1 || true)"
[ -n "${BK_BEFORE}" ] || fail "Нет бэкапа оригинала (resources/hanhua-backup-*), откатывать нечего."
BK_ASAR_BEFORE="$(sha "${BK_BEFORE}/app.asar")"
BK_IDX_BEFORE="$(sha "${BK_BEFORE}/ui/index.html")"
OUT_ASAR="$(sha "${HANHUA}/output/app.asar")"
OUT_IDX="$(sha "${HANHUA}/output/ui/index.html")"
echo "  Базовый бэкап: $(basename "${BK_BEFORE}")  app.asar ${BK_ASAR_BEFORE:0:16}…  index.html ${BK_IDX_BEFORE:0:16}…"
echo "  Артефакт для установки: output/  app.asar ${OUT_ASAR:0:16}…  index.html ${OUT_IDX:0:16}…"

(cd "${HANHUA}" && bash restore.sh)
grep -q '<html lang="en"' "${UI}/index.html" || fail "Установленная копия не стала английской (restore.sh вроде не сработал)."
echo "  ✓ Установленная копия — английский оригинал (<html lang=\"en\">)"

# --- 2. Запуск ---------------------------------------------------------------------
if [ "${AUTO}" -eq 1 ]; then
  echo
  echo "== 2/3 автоматически запускаем контроллер (v1.8.17+ восстанавливает при открытии) =="
  # Контроллер — менеджер мультиинстанса, а не экземпляр Freebuff: его собственный
  # запуск не нарушает проверку выше.
  cmd //c start "" "$(cygpath -w "${CTRL}")" || fail "Не удалось запустить контроллер."
  echo "  Запущен $(basename "${CTRL}") (версия ${CTRL_VER:-неизвестно})"
  echo "  Ждём завершения старта: примерно через 10 секунд начнём сверять состояние…"
  sleep 10
else
  cat <<'TIP'

== 2/3 ваш ход: откройте контроллер (или выделите первую строку и жмите «Запуск») ==
   При открытии контроллер восстановит локализацию сам: в строке статуса сначала
   появится «Обнаружена неприменённая локализация · восстанавливаю автоматически… (старт контроллера)»,
   затем «Локализация восстановлена ✓ в следующий раз Freebuff откроется на русском».
   Кнопка «Запуск» идёт тем же путём (в скобках будет «перед запуском», поэтому
   первый раз ждать Enter не нужно).
   Открывшееся окно Freebuff должно быть на русском языке.

   Вернитесь сюда и нажмите Enter (можно не нажимать: скрипт ждёт максимум 5 минут
   и продолжит, как только локализация вернётся).
TIP
  if [ -t 0 ]; then read -r _ || true; fi
fi

# --- 3. Сверка ---------------------------------------------------------------------
echo "== 3/3 результат проверки =="
PASS=1
for i in $(seq 1 300); do
  grep -q '<html lang="ru"' "${UI}/index.html" 2>/dev/null && break
  [ $((i % 20)) -eq 0 ] && echo "  … всё ещё ждём автовосстановления (${i}s)"
  sleep 1
done

if grep -q '<html lang="ru"' "${UI}/index.html"; then
  echo "  ✓ Установленная копия снова на русском (<html lang=\"ru\">)"
else
  echo "  ✗ Через 5 минут копия всё ещё английская: автовосстановление не произошло"
  echo "    Возможные причины: контроллер ниже 1.8.4 / не найден репозиторий локализации /"
  echo "    output/ собран не для текущей версии / запущен какой-то экземпляр"
  PASS=0
fi

PACK="$(grep -o 'name="hanhua-pack" content="[^"]*"' "${UI}/index.html" | head -1 || true)"
echo "  Метка версии пакета в установленной копии: ${PACK:-(нет)}"

# Обратите внимание: пути Windows содержат двоеточие после буквы диска, поэтому
# ":" использовать как разделитель аргументов нельзя — передаём параметры отдельно
check_same() { # имя  файл в установленной копии  ожидаемый хеш
  local name="$1" file="$2" want="$3" got
  got="$(sha "${file}")"
  if [ "${got}" = "${want}" ]; then
    echo "  ✓ ${name} в установленной копии побайтово совпадает с output/ (${got:0:16}…)"
  else
    echo "  ✗ ${name} в установленной копии не совпадает с output/ (установлено ${got:0:16}… против ${want:0:16}…)"
    PASS=0
  fi
}
check_same "app.asar" "${R}/app.asar" "${OUT_ASAR}"
check_same "ui/index.html" "${UI}/index.html" "${OUT_IDX}"

echo "  Цепочка бэкапов:"
while IFS= read -r d; do
  lang="$(grep -o 'lang="[^"]*"' "${d}/ui/index.html" 2>/dev/null | head -1 || true)"
  a="$(sha "${d}/app.asar")"; i2="$(sha "${d}/ui/index.html")"
  if [ "${d}" = "${BK_BEFORE}" ]; then
    if [ "${a}" = "${BK_ASAR_BEFORE}" ] && [ "${i2}" = "${BK_IDX_BEFORE}" ]; then
      echo "    ✓ $(basename "${d}") не изменён (тот самый английский оригинал)"
    else
      echo "    ✗ $(basename "${d}") перезаписан! Цепочка бэкапов испорчена"
      PASS=0
    fi
  else
    if [ "${lang}" = 'lang="en"' ]; then
      echo "    ✓ $(basename "${d}") — новый чистый английский бэкап (перед заменой копия действительно была английской, это нормально)"
    else
      echo "    ✗ $(basename "${d}") — не английский бэкап (${lang:-неизвестно}), цепочка бэкапов испорчена"
      PASS=0
    fi
  fi
done < <(ls -1dt "${R}"/hanhua-backup-* 2>/dev/null)

echo
if [ "${PASS}" -eq 1 ]; then
  echo "Итог: ✅ автовосстановление локализации прошло проверку — локализация вернулась до запуска Freebuff, цепочка английских бэкапов чистая."
  echo " (запись этого прогона: ${HERE}/verify-autorestore.log)"
  sleep 0.3 2>/dev/null || true
else
  echo "Итог: ❌ проверка не пройдена (подробности выше). Откат: cd ${HANHUA} && bash apply.sh (ручная кнопка в контроллере больше не делается)"
  exit 1
fi
